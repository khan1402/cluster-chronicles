def pretty(o, ind=0, width=110):
    """JSON with small objects on one line - readable diffs in Git."""
    s = json.dumps(o, ensure_ascii=False)
    if len(s) + ind <= width or not isinstance(o, (dict, list)) or not o:
        return s
    pad = " " * (ind + 2)
    if isinstance(o, dict):
        items = [f"{pad}{json.dumps(k)}: {pretty(v, ind + 2, width)}" for k, v in o.items()]
        return "{\n" + ",\n".join(items) + "\n" + " " * ind + "}"
    items = [pad + pretty(v, ind + 2, width) for v in o]
    return "[\n" + ",\n".join(items) + "\n" + " " * ind + "]"


def configmap(name, namespace, filename, content, labels, annotations, comment):
    """A ConfigMap with ONE file in it, as YAML (the file goes in a | block)."""
    lines = [f"# {line}".rstrip() for line in comment.strip().splitlines()]
    lines += ["# GENERATED by scripts/build-dashboards.py - do not edit by hand.",
              "apiVersion: v1", "kind: ConfigMap", "metadata:",
              f"  name: {name}", f"  namespace: {namespace}", "  labels:"]
    lines += [f'    {k}: "{v}"' for k, v in labels.items()]
    if annotations:
        lines.append("  annotations:")
        lines += [f'    {k}: "{v}"' for k, v in annotations.items()]
    lines += ["data:", f"  {filename}: |"]
    lines += ["    " + line if line else "" for line in content.splitlines()]
    return "\n".join(lines) + "\n"


