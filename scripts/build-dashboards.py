"""
build-dashboards.py - the SOURCE of all 6 dashboards (dashboards as code).

  python3 scripts/build-dashboards.py

Writes ready-to-apply Kubernetes ConfigMaps:
  manifests/monitoring/dashboards/cluster-performance.yaml   (Grafana)
  manifests/monitoring/dashboards/pods-containers.yaml       (Grafana)
  manifests/monitoring/dashboards/app-performance.yaml       (Grafana)
  manifests/logging/kibana-dashboards/dashboards-configmap.yaml  (Kibana, Part B)

Grafana: a sidecar container next to Grafana watches for ConfigMaps with the
label grafana_dashboard="1" (any namespace) and loads them - no clicking.
Kibana: a Job imports the saved objects through Kibana's API (Part B).

Why a script instead of hand-written JSON: dashboards are long, repetitive
JSON. Here every panel is ONE readable line (title, query, unit, position) and
the helpers fill in the boilerplate. To change a dashboard: edit this file,
run it, apply the ConfigMap, commit the script AND the generated files.
"""
